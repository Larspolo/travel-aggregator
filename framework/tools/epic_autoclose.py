#!/usr/bin/env python3
"""Close an epic by itself when the tickets of its last criteria merge (#835, #617).

The epic check (`queue.md`, "Epics and refill") ends its comment with the line `Close this epic when #N merges.` when
all other criteria are met, or `Close this epic when #N and #M merge.` (also `#N, #M and #K`) when they wait for more
than one ticket (#617: the whole test and the README of #559 cost one more deep run). When each of them then closes as
completed by a merged PR, and the epic has no other open sub-issue
and no open "Part of #E" ticket, `close.yml` runs this tool: an evidence comment and the label `close`. Before this, the
pacer started one more deep run only to read the criteria again (7 % of the list price of 100 PRs, 2026-11-03).

    python3 framework/tools/epic_autoclose.py            # print the epics that close, change nothing
    python3 framework/tools/epic_autoclose.py --apply    # comment, add the label `close`; stdout: the epic numbers

The selection functions take plain JSON and functions for the reads, so the tests need no network.
"""
import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

# "after": the form of #813; a list of tickets: "#N and #M merge" (#617)
LINE = re.compile(r"(?:^|\s)Close this epic (?:when|after) (#\d+(?:(?:,| and|, and) #\d+)*) merges?\.$")
AGENT = "Generated by [Claude Code]"      # the footer of each agent comment (`feedback.AGENT`)


def own_text(comment):
    """The body with no quoted lines (">"): a quote reply copies the footer of an agent comment (#3068)."""
    return "\n".join(line for line in (comment.get("body") or "").splitlines() if not line.lstrip().startswith(">"))


def by_agent(comment):
    """A comment of a run: a login of `owners` (the runs post as the owner) with the footer, or the app "claude" (`gh api`
    of a cloud run, `feedback.by_owner`). Any user can write the footer: the login keeps a stranger from closing an epic."""
    from agent_config import owners
    return (comment.get("user") or {}).get("login") in owners() and \
        (AGENT in own_text(comment) or bool(comment.get("performed_via_github_app")))


def by_bot(comment):
    """A comment of a workflow (github-actions[bot]): no run and no owner wrote it."""
    return (comment.get("user") or {}).get("type") == "Bot" and not comment.get("performed_via_github_app")


def close_line(comments):
    """(N, ...) of `Close this epic when #N merges.` (or `#N and #M merge.`) at the end of the last comment of a run or
    a person, else None.
    A later comment of a person (an owner question) needs a run: then None. The footer does not count."""
    last = next((c for c in reversed(comments) if not by_bot(c)), None)
    if not last or not by_agent(last):
        return None
    text = own_text(last).split("\n---\n_Generated by")[0]
    lines = [line.strip() for line in text.splitlines() if line.strip()]
    m = LINE.search(lines[-1]) if lines else None
    return tuple(int(n) for n in re.findall(r"#(\d+)", m[1])) if m else None


def checks(issues, now=None):
    """The open epics that wait for an epic check (`usage.refill_need`): no open sub-issue, no open "Part of #E"
    ticket, no hold."""
    import usage
    return usage.epic_checks(issues, now)


def select(issues, comments_of, merged_pr, now=None):
    """[(E, (N, ...), (PR, ...), comment)]: each epic of `checks` whose last comment ends with the close line and whose
    tickets all merged. comments_of(E): the comments of E; merged_pr(N): the merged PR that closed #N as completed,
    else None."""
    out = []
    for e in checks(issues, now):
        comments = comments_of(e)
        ns = close_line(comments)
        if ns is None:
            continue
        prs = _all_merged(ns, merged_pr)
        if prs:
            out.append((e, ns, prs, next(c for c in reversed(comments) if not by_bot(c))))
    return out


def _all_merged(ns, merged_pr):
    """(PR, ...) of the tickets ns when each one merged, else None (one open or not planned: the epic check runs)."""
    prs = []
    for n in ns:
        pr = merged_pr(n)
        if not pr:
            return None
        prs.append(pr)
    return tuple(prs)


# ---- GitHub REST ----------------------------------------------------------------------------
def comments_of(number):
    import dashboard
    return dashboard.pages(f"issues/{number}/comments")


def merged_pr(number):
    """The number of the merged PR that closed #number as completed, else None (closed as not planned, by hand, open)."""
    import dashboard
    issue = dashboard.api(f"issues/{number}")
    if issue.get("state") != "closed" or issue.get("state_reason") != "completed":
        return None
    closed = [e for e in dashboard.pages(f"issues/{number}/events") if e.get("event") == "closed"]
    sha = closed[-1].get("commit_id") if closed else None
    if not sha:
        return None
    prs = [p for p in dashboard.api(f"commits/{sha}/pulls") if p.get("merged_at")]
    return prs[0]["number"] if prs else None


def ready(epic):
    """((N, ...), (PR, ...)) when the open epic closes by itself (the pacer skips its epic check), else None. An
    error: None."""
    try:
        ns = close_line(comments_of(epic))
        prs = _all_merged(ns, merged_pr) if ns is not None else None
        return (ns, prs) if prs else None
    except Exception as e:                                  # a GitHub error: the epic check runs as before
        print(f"epic autoclose #{epic}: {e}", file=sys.stderr)
        return None


def evidence(ns, prs, comment):
    left = " and ".join(f"#{n}" for n in ns)
    merged = " and ".join(f"PR #{pr}" for pr in prs)
    return (f"All criteria are met: the epic check ({comment.get('html_url', 'the last agent comment')}) left only {left}, "
            f"and {merged} merged {'it' if len(ns) == 1 else 'them'}. Closed by `close.yml` (`framework/tools/epic_autoclose.py`, #835). The roadmap "
            "line of this epic gets `[x]` in the next roadmap review.")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--apply", action="store_true", help="comment and add the label close")
    args = ap.parse_args(argv)
    import dashboard
    for e, ns, prs, comment in select(dashboard.pages("issues?state=open"), comments_of, merged_pr):
        print(f"#{e}: " + ", ".join(f"#{n} merged by PR #{pr}" for n, pr in zip(ns, prs)), file=sys.stderr)
        if args.apply:
            dashboard.api(f"issues/{e}/comments", "POST", {"body": evidence(ns, prs, comment)})
            dashboard.api(f"issues/{e}/labels", "POST", {"labels": [dashboard.CLOSE]})
            print(e)
    return 0


if __name__ == "__main__":
    sys.exit(main())
